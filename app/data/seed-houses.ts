import type { House, HouseActivity, HouseImage } from '~/types/house'

const amenity = (key: string, label_es: string, label_en: string) => ({
  key,
  label_es,
  label_en,
})

const activity = (
  key: string,
  label_es: string,
  label_en: string,
  detail_es?: string,
  detail_en?: string,
): HouseActivity => ({
  key,
  label_es,
  label_en,
  detail_es,
  detail_en,
})

function gallery(houseId: string, paths: string[]): HouseImage[] {
  return paths.map((url, i) => ({
    id: `${houseId}-img-${i + 1}`,
    house_id: houseId,
    url,
    alt_es: null,
    alt_en: null,
    sort_order: i + 1,
  }))
}

